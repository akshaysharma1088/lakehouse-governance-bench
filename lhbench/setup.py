"""Create roles, warehouses, databases, tags and masking policies used by all experiments.

Run once as a user holding ACCOUNTADMIN (a Snowflake trial account works).
Everything created is prefixed LH_ and removed by teardown.py.
"""
from .common import connect, q, log, TPCH_DB, TPCH_SMALL, DRY_RUN

STATEMENTS = [
    # roles
    "CREATE ROLE IF NOT EXISTS LH_PII_READER",
    "CREATE ROLE IF NOT EXISTS LH_ENGINEER",      # domain engineer, legitimately reads PII
    "CREATE ROLE IF NOT EXISTS LH_ANALYST",       # consumer without PII entitlement
    "GRANT ROLE LH_PII_READER TO ROLE LH_ENGINEER",
    "GRANT ROLE LH_ENGINEER TO ROLE SYSADMIN",
    "GRANT ROLE LH_ANALYST TO ROLE SYSADMIN",
    # warehouses (auto-suspend after 60 s to save credits)
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_ADMIN  WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_PROBE  WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_E3     WAREHOUSE_SIZE=MEDIUM AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_SHARED WAREHOUSE_SIZE=MEDIUM AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE MAX_CLUSTER_COUNT=1",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_SHARED_MC WAREHOUSE_SIZE=MEDIUM AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE MIN_CLUSTER_COUNT=1 MAX_CLUSTER_COUNT=3 SCALING_POLICY=STANDARD",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_CUSTOMER WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_SALES    WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_FINANCE  WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    "CREATE WAREHOUSE IF NOT EXISTS LH_WH_SUPPLY   WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE",
    # governance database: tags, policies, contract registry
    "CREATE DATABASE IF NOT EXISTS LH_GOV",
    "CREATE SCHEMA IF NOT EXISTS LH_GOV.POLICIES",
    "CREATE SCHEMA IF NOT EXISTS LH_GOV.REGISTRY",
    "CREATE TABLE IF NOT EXISTS LH_GOV.REGISTRY.CONTRACTS (DB STRING, DOMAIN STRING, TABLE_NAME STRING, CONTRACT VARIANT, PUBLISHED_AT TIMESTAMP_LTZ)",
    "CREATE TAG IF NOT EXISTS LH_GOV.POLICIES.PII_CLASS ALLOWED_VALUES 'name','address','phone','balance','employee'",
    """CREATE MASKING POLICY IF NOT EXISTS LH_GOV.POLICIES.MP_STR_DIRECT AS (val STRING) RETURNS STRING ->
         CASE WHEN IS_ROLE_IN_SESSION('LH_PII_READER') THEN val ELSE '***MASKED***' END""",
    """CREATE MASKING POLICY IF NOT EXISTS LH_GOV.POLICIES.MP_NUM_DIRECT AS (val NUMBER(12,2)) RETURNS NUMBER(12,2) ->
         CASE WHEN IS_ROLE_IN_SESSION('LH_PII_READER') THEN val ELSE NULL END""",
    """CREATE MASKING POLICY IF NOT EXISTS LH_GOV.POLICIES.MP_STR_TAG AS (val STRING) RETURNS STRING ->
         CASE WHEN IS_ROLE_IN_SESSION('LH_PII_READER') THEN val ELSE '***MASKED***' END""",
    """CREATE MASKING POLICY IF NOT EXISTS LH_GOV.POLICIES.MP_NUM_TAG AS (val NUMBER(12,2)) RETURNS NUMBER(12,2) ->
         CASE WHEN IS_ROLE_IN_SESSION('LH_PII_READER') THEN val ELSE NULL END""",
    # experiment databases
    "CREATE DATABASE IF NOT EXISTS LH_E1_CENTRAL",
    "CREATE DATABASE IF NOT EXISTS LH_E1_DOMAIN",
    "CREATE DATABASE IF NOT EXISTS LH_E3",
    "CREATE SCHEMA IF NOT EXISTS LH_E3.SALES",
    "CREATE SCHEMA IF NOT EXISTS LH_E3.FINANCE",
    # grants
    "GRANT USAGE ON WAREHOUSE LH_WH_PROBE TO ROLE LH_ANALYST",
    "GRANT USAGE ON WAREHOUSE LH_WH_E3 TO ROLE LH_ANALYST",
    "GRANT USAGE ON WAREHOUSE LH_WH_E3 TO ROLE LH_ENGINEER",
    "GRANT USAGE ON WAREHOUSE LH_WH_PROBE TO ROLE LH_ENGINEER",
]
for db in ("LH_E1_CENTRAL", "LH_E1_DOMAIN", "LH_E3"):
    STATEMENTS += [
        f"GRANT USAGE ON DATABASE {db} TO ROLE LH_ANALYST",
        f"GRANT USAGE ON FUTURE SCHEMAS IN DATABASE {db} TO ROLE LH_ANALYST",
        f"GRANT USAGE ON ALL SCHEMAS IN DATABASE {db} TO ROLE LH_ANALYST",
        f"GRANT SELECT ON FUTURE TABLES IN DATABASE {db} TO ROLE LH_ANALYST",
        f"GRANT SELECT ON FUTURE VIEWS IN DATABASE {db} TO ROLE LH_ANALYST",
    ]
STATEMENTS += [
    "GRANT USAGE ON DATABASE LH_E3 TO ROLE LH_ENGINEER",
    "GRANT USAGE ON ALL SCHEMAS IN DATABASE LH_E3 TO ROLE LH_ENGINEER",
    "GRANT CREATE TABLE, CREATE VIEW ON SCHEMA LH_E3.FINANCE TO ROLE LH_ENGINEER",
    "GRANT SELECT ON FUTURE TABLES IN SCHEMA LH_E3.SALES TO ROLE LH_ENGINEER",
]

TAG_BINDINGS = [
    "ALTER TAG LH_GOV.POLICIES.PII_CLASS SET MASKING POLICY LH_GOV.POLICIES.MP_STR_TAG",
    "ALTER TAG LH_GOV.POLICIES.PII_CLASS SET MASKING POLICY LH_GOV.POLICIES.MP_NUM_TAG",
]


def run():
    conn = connect()
    q(conn, "CREATE WAREHOUSE IF NOT EXISTS LH_WH_ADMIN WAREHOUSE_SIZE=XSMALL AUTO_SUSPEND=60 INITIALLY_SUSPENDED=TRUE")
    q(conn, "USE WAREHOUSE LH_WH_ADMIN")
    # sample data is normally present; recreate it from the share if not
    if not DRY_RUN and not q(conn, f"SHOW DATABASES LIKE '{TPCH_DB}'"):
        log("sample database missing, creating it from the SFC_SAMPLES share")
        q(conn, f"CREATE DATABASE {TPCH_DB} FROM SHARE SFC_SAMPLES.SAMPLE_DATA")
    q(conn, f"SELECT COUNT(*) FROM {TPCH_DB}.{TPCH_SMALL}.NATION")
    for s in STATEMENTS:
        q(conn, s)
    for s in TAG_BINDINGS:
        try:
            q(conn, s)
        except Exception as e:  # already bound on a rerun
            if "already" not in str(e).lower():
                raise
    q(conn, "SET LH_ME = CURRENT_USER()")
    for r in ("LH_ANALYST", "LH_ENGINEER"):
        q(conn, f"GRANT ROLE {r} TO USER IDENTIFIER($LH_ME)")

    # self-test: masking must hide values from the analyst and show them to the engineer
    q(conn, "CREATE OR REPLACE SCHEMA LH_E1_DOMAIN.SELFTEST")
    q(conn, "CREATE OR REPLACE TABLE LH_E1_DOMAIN.SELFTEST.T (S STRING, N NUMBER(12,2)) AS SELECT 'secret', 12.5")
    q(conn, "ALTER TABLE LH_E1_DOMAIN.SELFTEST.T MODIFY COLUMN S SET TAG LH_GOV.POLICIES.PII_CLASS = 'phone'")
    q(conn, "ALTER TABLE LH_E1_DOMAIN.SELFTEST.T MODIFY COLUMN N SET TAG LH_GOV.POLICIES.PII_CLASS = 'balance'")
    q(conn, "GRANT SELECT ON TABLE LH_E1_DOMAIN.SELFTEST.T TO ROLE LH_ANALYST")
    if not DRY_RUN:
        a = connect(role="LH_ANALYST", warehouse="LH_WH_PROBE", secondary_none=True)
        row = q(a, "SELECT S, N FROM LH_E1_DOMAIN.SELFTEST.T")[0]
        assert row[0] == "***MASKED***" and row[1] is None, f"masking self-test failed for analyst: {row}"
        log("masking self-test passed (analyst sees masked values)")
    q(conn, "DROP SCHEMA LH_E1_DOMAIN.SELFTEST")
    log("setup complete")


if __name__ == "__main__":
    run()
